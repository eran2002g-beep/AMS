// src/models/Attendance.js - stores the final calculated attendance record for each employee per day created after roster processing matches AttendanceLog punches against RosterEntry schedules (Epic 4) this is what employees see when they view attendance and what admins manage (Epic 4 AC1)

const { DataTypes } = require('sequelize');
const sequelize     = require('../../config/db');
const { nextSequentialPublicId } = require('../utils/publicId');

const Attendance = sequelize.define('Attendance', {

    // id - internal primary key
    id: {
        type: DataTypes.INTEGER,
        primaryKey: true,
        autoIncrement: true,
    },

    // attendanceId - public-facing ID, auto-generated as ATT001, ATT002...
    attendanceId: {
        type: DataTypes.STRING,
        allowNull: false,
        unique: true,
    },

    // employeeId - public-facing employee ID e.g. EMP001
    // links this record to the employee - used for filtering attendance by employee (Epic 4 AC1)
    employeeId: {
        type: DataTypes.STRING,
        allowNull: false,
    },

    // date - the date this attendance record covers e.g. "2025-06-01"
    // used for date range and month filters in View Attendance (Epic 4 AC3)
    date: {
        type: DataTypes.DATEONLY,
        allowNull: false,
    },

    // month - extracted from date, stored separately for fast month-based filtering
    // e.g. date 2025-06-01 → month = 6
    month: {
        type: DataTypes.INTEGER,
        allowNull: false,
    },

    // year - extracted from date, stored with month for accurate year+month queries
    year: {
        type: DataTypes.INTEGER,
        allowNull: false,
    },

    // clockIn - the actual time the employee clocked in e.g. "08:03:00"
    // pulled from the matching AttendanceLog punch record after processing
    // null if the employee did not clock in at all
    clockIn: {
        type: DataTypes.TIME,
        allowNull: true, // null = no clock-in found (absent)
    },

    // clockOut - the actual time the employee clocked out e.g. "17:10:00"
    // null if the employee did not clock out
    clockOut: {
        type: DataTypes.TIME,
        allowNull: true, // null = no clock-out found
    },

    // scheduledStart - the shift start time from the matched RosterEntry e.g. "08:00:00"
    // stored here so attendance views can show scheduled vs actual side by side (Epic 4 View Roster Attendance)
    scheduledStart: {
        type: DataTypes.TIME,
        allowNull: true, // null if no roster was matched for this day
    },

    // scheduledEnd - the shift end time from the matched RosterEntry
    scheduledEnd: {
        type: DataTypes.TIME,
        allowNull: true,
    },

    // status - the final attendance status calculated during roster processing
    // present      = clocked in (on time or late — see lateCoverMinutes for time to make up)
    // absent       = no punch found for a scheduled shift
    // leave        = covered by an approved leave request
    // unauthorised = only one punch found (missing clock-in or clock-out)
    // holiday      = scheduled day off
    status: {
        type: DataTypes.ENUM('present', 'absent', 'leave', 'unauthorised', 'holiday'),
        allowNull: false,
    },

    // lateMinutes - how many minutes late the employee arrived vs scheduled start
    // e.g. shift 10:00, in 10:45 → 45
    lateMinutes: {
        type: DataTypes.INTEGER,
        allowNull: false,
        defaultValue: 0,
    },

    // lateCoverMinutes - minutes the employee still owes after shift processing
    // must stay until scheduledEnd + arrival lateness; early departure adds to this total
    // e.g. shift 08:00-17:00, in 08:20, out 17:00 → 20 min (should have left at 17:20)
    lateCoverMinutes: {
        type: DataTypes.INTEGER,
        allowNull: false,
        defaultValue: 0,
    },

    // rosterId - the roster this record was matched against during processing
    // links back to the Roster table - used for View Roster Attendance (Epic 4)
    rosterId: {
        type: DataTypes.INTEGER,
        allowNull: true, // null = manually added record with no roster
    },

    // attendanceLogId - the raw punch log this record was created from
    // links back to AttendanceLog - used for audit trail and editing
    attendanceLogId: {
        type: DataTypes.INTEGER,
        allowNull: true, // null = manually added by admin, no IoT log exists
    },

    // leaveRequestId - if status is 'leave', links to the approved leave request
    // used in Approve Leave Requests (Epic 4) to update attendance status automatically
    leaveRequestId: {
        type: DataTypes.INTEGER,
        allowNull: true, // null = no leave request linked
    },

    // notes - optional admin notes for manual additions or corrections
    // used in Add/Edit Attendance Records (Epic 4)
    notes: {
        type: DataTypes.TEXT,
        allowNull: true,
    },

    // isManual - flags records added manually by an admin vs auto-generated by processing
    // true = admin added this record manually (Epic 4: Add Attendance Records)
    // false = auto-created during roster processing
    isManual: {
        type: DataTypes.BOOLEAN,
        defaultValue: false,
    },

}, {
    tableName: 'attendance',
    timestamps: true, // createdAt and updatedAt track when records are added or edited

    hooks: {

        // beforeValidate runs before allowNull checks — must run here, not beforeCreate
        beforeValidate: async (attendance) => {
            if (!attendance.isNewRecord || attendance.attendanceId) return;

            attendance.attendanceId = await nextSequentialPublicId(
                Attendance, 'attendanceId', 'ATT'
            );
        },
    },
});

module.exports = Attendance;